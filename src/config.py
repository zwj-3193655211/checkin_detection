"""
checkin_detection 全局参数配置（单一权威来源）
================================================
项目所有可调参数集中于此文件。
修改后所有脚本（checkin_system.py / train_mlp.py / test_current.py）自动同步。

═══════════════════════════════════════════════════════════════
  温度参数 ≠ 模型权重 → 改温度不需要重训练！
  两个温度都在推理时生效： logit / temperature
═══════════════════════════════════════════════════════════════

参数速查：
  FEATURE_TEMPERATURE    : 特征预测器 MLP 推理温度（默认 1.8）
  CLASSIFIER_TEMPERATURE : 主分类器 MLP softmax 温度（默认 5.0）
  FEATURE_THRESHOLD      : 特征得分认定阈值（默认 0.60）
  ALPHA_AUTO_PASS        : 自动通过置信度阈值 - 规则1/2（默认 0.80）
  ALPHA_REVIEW           : 待审核置信度阈值 - 规则4（默认 0.85）
  MIN_FEATURES           : 最少匹配特征数 - 规则3（默认 3）
  RUN_FEATURE_THRESH     : 晨跑自动通过最少特征数 - 规则1（默认 5）
  READ_FEATURE_THRESH    : 晨读自动通过最少特征数 - 规则2（默认 3）
"""

# =====================================================================
# 【温度参数 - 不需重训练，直接修改即可生效】
# 温度只在推理时使用：sigmoid(logit / T) 或 softmax(logit / T)
# 改温度 → 重新推理即可，模型权重不变
# =====================================================================

# 特征预测器推理温度（控制 11 维特征 sigmoid 概率分布）
# 值越小 → 强特征更确定(趋近1.0)、弱特征更不确定(趋近0)
# 值越大 → 所有特征概率趋向 0.5（平滑）
FEATURE_TEMPERATURE: float = 1.8

# 主分类器 softmax 温度（控制晨读/晨跑二分类置信度分布）
# 值越大 → 置信度越低/更平滑，值越小 → 置信度越高/更集中
CLASSIFIER_TEMPERATURE: float = 5.0

# =====================================================================
# 【特征得分阈值 - 分晨读/晨跑两组】
# 晨读特征（索引0-3）：双峰分布，得分集中在~0.27或~0.78，0.66卡在双峰之间
# 晨跑特征（索引4-10）：单峰分布集中在~0.22，0.60合理
# =====================================================================

# 晨读特征得分认定阈值（人脸/蓝色桌面/教室/投影幕布）
FEATURE_THRESHOLD_READ: float = 0.66

# 晨跑特征得分认定阈值（跑道/树木/草地/树木/路灯/运动服布/主席台）
FEATURE_THRESHOLD_RUN: float = 0.60

# =====================================================================
# 【四规则决策阈值】
# =====================================================================

# 规则1/2: 自动通过置信度门槛（高于此值 + 特征足够 → 自动通过）
ALPHA_AUTO_PASS: float = 0.80

# 规则4:  待审核置信度门槛（低于此值 → 待审核）
ALPHA_REVIEW: float = 0.85

# =====================================================================
# 【特征数量阈值】
# =====================================================================

# 规则3: 最少匹配特征数（低于此值 → 待审核，不论置信度高低）
MIN_FEATURES: int = 3

# 规则1: 晨跑自动通过所需最少特征数
RUN_FEATURE_THRESH: int = 5

# 规则2: 晨读自动通过所需最少特征数
READ_FEATURE_THRESH: int = 3

# =====================================================================
# 【编码器选择 - Phase 5 系统接入】
# 切换部署系统使用的视觉编码器，无需改动 checkin_system 主干逻辑。
#   ENCODER ∈ {"CLIP", "SigLIP", "ViT-Tiny"}
#   - CLIP    : 通用基线（OpenAI ViT-B/32, 512维, CenterCrop）
#   - SigLIP  : SigLIP2-NaFlex-B/16（768维, 原生宽高比零裁切）
#   - ViT-Tiny: 本项目端到端自训（letterbox 零裁切）
# 注：CLIP 必须与产出 clip_features_cpu.csv 的 OpenAI CLIP 一致。
# =====================================================================
ENCODER: str = "CLIP"

# ViT-Tiny 默认使用的训练种子（Phase 3 多 seed 实验产出的最佳/代表权重）
VIT_TINY_SEED: int = 42

# SigLIP 模型目录（Phase 2 下载，已 gitignore）
SIGLIP_MODEL_DIR: str = "data/models/siglip2-base-patch16-naflex"
